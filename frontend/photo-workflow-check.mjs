import { chromium, expect } from '@playwright/test';
import path from 'node:path';
import { writeFile } from 'node:fs/promises';

const browser = await chromium.launch({ channel: 'msedge', headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
const artifacts = path.resolve('../artifacts');
try {
  await page.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' });
  const records = await (await page.request.get('http://127.0.0.1:8000/api/assessments')).json();
  const source = records.assessments.find((r) => r.name === 'National workflow verification (Johannesburg)' && ['complete', 'partial'].includes(r.status));
  if (!source) throw new Error('Run backend/check_workflow.py first.');
  const saved = await (await page.request.get(`http://127.0.0.1:8000/api/assessments/${source.id}`)).json();
  await page.getByRole('button', { name: 'Assessment library', exact: true }).click();
  await page.locator(`[data-assessment-id="${source.id}"]`).click();
  await expect(page.getByRole('heading', { name: source.name, exact: true })).toBeVisible();
  if (saved.result.overlay) await page.getByRole('checkbox', { name: 'NDVI', exact: true }).uncheck();
  await expect.poll(() => page.locator('.map-canvas').evaluate((el) => el.__assessmentMap?.areTilesLoaded()), { timeout: 30000 }).toBe(true);
  const photoPath = path.join(artifacts, 'photo-workflow-reference.jpg');
  await page.locator('.map-canvas').screenshot({ path: photoPath, type: 'jpeg' });
  await page.getByRole('button', { name: 'New assessment', exact: true }).click();
  await page.locator('input[type="file"][accept="image/jpeg,image/png,image/webp"]').setInputFiles(photoPath);
  await expect(page.getByText('No GPS metadata found', { exact: true })).toBeVisible();
  await expect(page.getByText('Possible visible features · AI interpretation', { exact: true })).toBeVisible({ timeout: 120000 });
  await page.getByRole('button', { name: 'Start assessment' }).click();
  await expect(page.getByText('The assessment has not started yet', { exact: true })).toBeVisible();
  await page.locator('input[type="file"][accept=".geojson,.json,application/geo+json"]').setInputFiles({ name: 'verification-boundary.geojson', mimeType: 'application/geo+json', buffer: Buffer.from(JSON.stringify(saved.site.geometry)) });
  await page.getByRole('textbox', { name: /Assessment name/ }).fill('Photo and local AI workflow verification');
  await page.getByLabel(/First year/).fill(String(saved.options.start_year));
  await page.getByLabel(/Last complete year/).fill(String(saved.options.end_year));
  await page.getByLabel(/Comparable season/).selectOption(String(saved.options.season_month));
  await page.getByRole('textbox', { name: /Property or farm/ }).fill('Engineering fixture - no verified title record');
  await page.getByLabel(/Site notes/).fill('Engineering test using a map screenshot as the uploaded image, not a ground photograph. Location confirmed manually for workflow verification only.');
  await page.getByRole('checkbox', { name: /I have checked the map/ }).check();
  await page.getByRole('button', { name: 'Start assessment' }).click();
  await expect(page.getByRole('heading', { name: 'Water, vegetation and the ground' })).toBeVisible({ timeout: 180000 });
  await expect(page.getByText(/Its connection to this land is based on your map confirmation/)).toBeVisible();
  await expect(page.getByRole('heading', { name: 'photo-workflow-reference.jpg' })).toBeVisible();
  await page.screenshot({ path: path.join(artifacts, 'upgraded-report-desktop.png') });
  await page.getByRole('tab', { name: 'History & change', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Current and previous owners' })).toBeVisible();
  await expect(page.getByText('Engineering fixture - no verified title record', { exact: false })).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1)) throw new Error('Mobile report overflows');
  await page.getByRole('tab', { name: 'Land overview', exact: true }).click();
  await page.screenshot({ path: path.join(artifacts, 'upgraded-report-mobile.png') });
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Export evidence' }).click();
  const download = await downloadEvent;
  await download.saveAs(path.join(artifacts, 'photo-workflow-report.json'));
  if (errors.length) throw new Error(errors.join('; '));
  await writeFile(path.join(artifacts, 'photo-workflow-check.txt'), 'PASS: local vision, photo upload, manual location confirmation, boundary import, real assessment submission, property reference, photo report, history, mobile layout and JSON export.\n');
  console.log('PASS: local vision, photo upload, manual location, real assessment submission, property reference, report, mobile layout and export.');
} catch (error) {
  await page.screenshot({ path: path.join(artifacts, 'photo-workflow-failure.png') });
  console.log((await page.locator('body').innerText()).slice(0, 2000));
  throw error;
} finally { await browser.close(); }
